//! CONCEPT: contracts crate (WP-2). The shared types every other crate exchanges (PRD §6), generated from
//!          proto/contracts.proto; parsers that turn llama.cpp's text output into those types; and the
//!          generated SpacetimeDB client bindings for the control module (crates/control).
//! WHY: D-13 (6:10pm): the control plane is a SpacetimeDB module. Agents (WP-3) and the coordinator (WP-4) are
//!      its clients; they all compile this one crate, so they can't disagree on a shape. The .proto is kept as
//!      the type schema only (no services; Aries correction on #11, 6:03pm).
//! DEPENDS ON: build.rs (prost codegen via protox), proto/contracts.proto, src/control/ (generated by
//!      `spacetime generate` from crates/control and committed, so no machine but main needs the CLI).
//! AFFECTS: agent, coordinator, planner, relay, bench, netcheck. See CONTRACTS.md for the shapes in prose.
//!
//! Layout:
//! - `v1`: generated §6 messages and enums, re-exported at the crate root (`contracts::Heartbeat`).
//! - `json`: serde adapters so every message reads and writes the §6 JSON form (`serde_json::to_string`).
//! - `parsers`: llama.cpp text output -> contract types (WP-2 R2.4).
//! - `control`: SpacetimeDB client bindings (`DbConnection`, table handles, reducer calls, row types such as
//!   `NodeRow`). Not re-exported at the root on purpose: row/arg names live in their own namespace.
//! - `control_glue`: builds the reducer argument structs from §6 types (`node_info`, `heartbeat_info`).

